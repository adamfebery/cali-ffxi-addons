-- Writes `t` as `return { [key] = { [key2] = {field = n, ...}, ... }, ... }`.
-- Two levels of keys, then flat tables of numbers - enough for fixes and
-- calibration.
local function save_table(rel, header, t)
    local function key(k)
        return type(k) == 'number' and ('[%d]'):format(k) or ('[%q]'):format(k)
    end
    local function flat(p)
        local parts, names = {}, {}
        for k in pairs(p) do names[#names + 1] = k end
        table.sort(names)
        for _, k in ipairs(names) do
            parts[#parts + 1] = ('%s = %.2f'):format(k, p[k])
        end
        return '{' .. table.concat(parts, ', ') .. '}'
    end
    local lines = {header, 'return {'}
    for k1, inner in pairs(t) do
        lines[#lines + 1] = ('    %s = {'):format(key(k1))
        for k2, v in pairs(inner) do
            if type(v) == 'table' and v[1] then
                lines[#lines + 1] = ('        %s = {'):format(key(k2))
                for _, p in ipairs(v) do
                    lines[#lines + 1] = '            ' .. flat(p) .. ','
                end
                lines[#lines + 1] = '        },'
            else
                lines[#lines + 1] = ('        %s = %s,'):format(key(k2), flat(v))
            end
        end
        lines[#lines + 1] = '    },'
    end
    lines[#lines + 1] = '}'

    local f, err = io.open(windower.addon_path .. rel, 'w')
    if not f then
        say('could not write ' .. rel .. ': ' .. tostring(err))
        return
    end
    f:write(table.concat(lines, '\n'), '\n')
    f:close()
end

