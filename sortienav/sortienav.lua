local function load_lua(rel)
    local path = windower.addon_path .. rel
    if not windower.file_exists(path) then
        return nil, 'missing ' .. rel
    end
    local chunk, err = loadfile(path)
    if not chunk then
        return nil, err
    end
    local ok, result = pcall(chunk)
    if not ok then
        return nil, result
    end
    return result
end

