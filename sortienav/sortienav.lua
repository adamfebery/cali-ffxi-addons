local ALT_KEYS = S{56, 184}   -- DIK_LMENU, DIK_RMENU
local alt_held = false
local drag     -- {dx, dy} grab offset while dragging

windower.register_event('keyboard', function(dik, pressed)
    if ALT_KEYS:contains(dik) then
        alt_held = pressed
    end
end)

local MOUSE_MOVE, MOUSE_LEFT_DOWN, MOUSE_LEFT_UP = 0, 1, 2

-- One //sn cal click: pair where you stand with the image pixel clicked.
local function record_cal_point(sx, sy)
    local me = windower.ffxi.get_mob_by_target('me')
    local v = current_view
    if not me or not v or not v.image then
        return
    end
    local p = {x = me.x, y = me.y, z = me.z, u = (sx - v.ox) / v.k, v = (sy - v.oy) / v.k}
    local pts = calibrating.points

    if #pts == 1 then
        local dx, dy = math.abs(p.x - pts[1].x), math.abs(p.y - pts[1].y)
        if dx < 20 or dy < 20 then
            say(('point 2 is only %d / %d yalms from point 1 (east-west / north-south). '
                .. 'Move at least 20 both ways - diagonally across a big room - and click again.'):format(dx, dy))
            return
        end
    end
    pts[#pts + 1] = p
    say(('point %d: you at %.1f, %.1f  = pixel %d, %d'):format(#pts, p.x, p.y, p.u, p.v))
    if #pts < 2 then
        say('now walk well away diagonally (20+ yalms north/south AND east/west), then Alt+click again')
        return
    end

    calibration[calibrating.image] = {cal = pts}
    save_calibration()
    -- Sanity check: FFXI maps use one scale for both axes, so a big
    -- mismatch means a click was off.
    local T = transform(calibrating.floor)
    local ratio = T and math.abs(T.su / T.sv) or 0
    if ratio < 0.85 or ratio > 1.15 then
        say(('saved, but the two axes disagree (ratio %.2f) - a click was probably off. '
            .. '//sn cal to redo it.'):format(ratio))
    else
        say(('%s calibrated (%.2f px per yalm). You should now see your green dot on the map.'):format(
            calibrating.floor.label or calibrating.floor.id, math.abs(T.su)))
    end
    calibrating = nil
end

windower.register_event('mouse', function(kind, x, y)
    local view = settings.map_mode == 'large' and settings.large or settings.small

    if kind == MOUSE_LEFT_DOWN then
        if alt_held and settings.visible
                and x >= view.x and x <= view.x + view.size
                and y >= view.y and y <= view.y + view.size then
            if calibrating then
                record_cal_point(x, y)
            else
                drag = {dx = x - view.x, dy = y - view.y}
            end
            return true   -- swallow the click so the game doesn't see it
        end
    elseif kind == MOUSE_MOVE and drag then
        view.x, view.y = x - drag.dx, y - drag.dy
        last_update = 0   -- redraw next frame, not at the 5/sec rate
        return true
    elseif kind == MOUSE_LEFT_UP and drag then
        drag = nil
        config.save(settings)
        return true
    end
end)

windower.register_event('prerender', function()
    local now = os.clock()
    if now - last_update < 1 / settings.updates_per_sec then
        return
    end
    last_update = now

    if not settings.visible then
        return
    end
    local me = windower.ffxi.get_mob_by_target('me')
    local info = windower.ffxi.get_info()
    if not me or not info or not info.logged_in then
        hide_all()
        return
    end
    local floor = detect_floor(info.zone, me.x, me.y, me.z)
    try_advance(me, info.zone, floor)
    render_readout(me, info.zone, floor)
    render_map(me, info.zone, floor)
end)

