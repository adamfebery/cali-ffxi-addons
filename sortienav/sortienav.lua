local function zone_floors(zone_id)
    local z = zones[zone_id] or zone_maps[zone_id]
    return z and z.floors or {}
end

local function floor_by_id(zone_id, id)
    for _, f in ipairs(zone_floors(zone_id)) do
        if f.id == id then
            return f
        end
    end
end

local function floor_cal(floor)
    local m = floor and floor.map
    if not m then
        return nil
    end
    local saved = m.image and calibration[m.image]
    return saved and saved.cal or m.cal
end

local floor_override    -- set by //sn floor <id>

-- Which floor you are on:
--   1. //sn floor <id>, if set
--   2. a floor whose explicit z range / rectangle contains you
--   3. the calibrated floor whose calibration height is within 12 yalms of
--      yours (so ground floor vs basement sorts itself out once both are
--      calibrated)
--   4. otherwise the first floor not calibrated yet - e.g. you walked down
--      to a basement nobody has calibrated - so you can calibrate it
--   5. the zone's first floor
local function detect_floor(zone_id, x, y, z)
    local floors = zone_floors(zone_id)
    if floor_override then
        local f = floor_by_id(zone_id, floor_override)
        if f then
            return f
        end
    end
    for _, f in ipairs(floors) do
        local zr, r = f.z, f.rect
        if (zr or r) and (not zr or (z >= zr[1] and z <= zr[2]))
                and (not r or (x >= r[1] and x <= r[3] and y >= r[2] and y <= r[4])) then
            return f
        end
    end
    local best, best_d, uncalibrated
    for _, f in ipairs(floors) do
        local cal = floor_cal(f)
        if cal and cal[1] and cal[1].z then
            local d = math.abs(z - cal[1].z)
            if not best_d or d < best_d then
                best, best_d = f, d
            end
        elseif not uncalibrated then
            uncalibrated = f
        end
    end
    if best and best_d <= 12 then
        return best
    end
    return uncalibrated or best or floors[1]
end

-- FFXI maps are axis-aligned, so two calibration points give a scale and
-- offset per axis: u = su*x + ou, v = sv*y + ov (v grows downward).
local function transform(floor)
    local cal = floor_cal(floor)
    if not cal or not cal[1] or not cal[2] then
        return nil
    end
    local a, b = cal[1], cal[2]
    if a.x == b.x or a.y == b.y then
        return nil
    end
    local su = (b.u - a.u) / (b.x - a.x)
    local sv = (b.v - a.v) / (b.y - a.y)
    return {su = su, ou = a.u - su * a.x, sv = sv, ov = a.v - sv * a.y}
end

local function to_px(T, x, y)
    return T.su * x + T.ou, T.sv * y + T.ov
end

local function to_game(T, u, v)
    return (u - T.ou) / T.su, (v - T.ov) / T.sv
end

-- "H-8" -> centre of that cell in image pixels. Needs only map.grid =
-- {u0 =, v0 =, cell =} (grid's top-left corner and cell size in pixels),
-- so guide squares can be drawn on the map before it is calibrated.
local function grid_to_px(floor, grid)
    local g = floor and floor.map and floor.map.grid
    if not g or not grid then
        return nil
    end
    local letter, row = grid:upper():match('^%s*(%a)%s*%-?%s*(%d+)%s*$')
    if not letter then
        return nil
    end
    local col = letter:byte() - ('A'):byte()
    return g.u0 + (col + 0.5) * g.cell, g.v0 + (tonumber(row) - 0.5) * g.cell
end

-- The same cell centre in game x, y - this one needs the calibration.
local function grid_to_game(floor, grid)
    local T = transform(floor)
    local u, v = grid_to_px(floor, grid)
    if not T or not u then
        return nil
    end
    return to_game(T, u, v)
end

local function game_to_grid(floor, x, y)
    local T = transform(floor)
    local g = floor and floor.map and floor.map.grid
    if not T or not g then
        return nil
    end
    local u, v = to_px(T, x, y)
    local col = math.floor((u - g.u0) / g.cell)
    local row = math.floor((v - g.v0) / g.cell) + 1
    return string.char(('A'):byte() + col) .. '-' .. row
end

