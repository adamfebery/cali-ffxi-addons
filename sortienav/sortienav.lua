local route, route_name, step

local function wp_zone(wp)
    return wp.zone or route.zone
end

-- Position of waypoint i: a //sn fix beats an exact pos, which beats a guide
-- grid square. Returns x, y, z (z may be nil), source.
local function wp_pos(i)
    local wp = route.waypoints[i]
    local fix = fixes[route_name] and fixes[route_name][wp.id]
    if fix then
        return fix.x, fix.y, fix.z, 'fix'
    end
    if wp.pos then
        return wp.pos[1], wp.pos[2], wp.pos[3], 'pos'
    end
    if wp.grid then
        local zone = wp_zone(wp)
        local x, y = grid_to_game(floor_by_id(zone, wp.floor) or zone_floors(zone)[1], wp.grid)
        if x then
            return x, y, nil, 'grid'
        end
    end
end

local function set_route(name, r)
    if type(r) ~= 'table' or type(r.waypoints) ~= 'table' or #r.waypoints == 0 then
        say('route "' .. name .. '" has no waypoints')
        return
    end
    for i, wp in ipairs(r.waypoints) do
        wp.id = wp.id or i
    end
    -- A route without a zone binds to wherever you load it (handy for tests).
    r.zone = r.zone or windower.ffxi.get_info().zone
    route, route_name, step = r, name, 1
    say(('loaded "%s" - %d waypoints. Next: %s'):format(name, #r.waypoints, r.waypoints[1].name or '#1'))
end

local function advance(n, why)
    if not route then
        return
    end
    step = math.max(1, math.min(#route.waypoints + 1, step + n))
    local wp = route.waypoints[step]
    if wp then
        say(('[%d/%d] %s%s'):format(step, #route.waypoints, wp.name or ('#' .. step),
            why and (' (' .. why .. ')') or ''))
    else
        say('route "' .. route_name .. '" complete')
    end
end

local function list_routes()
    local files = windower.get_dir(windower.addon_path .. 'data/routes/') or {}
    local names = {}
    for _, f in ipairs(files) do
        local n = f:match('^(.+)%.lua$')
        if n then
            names[#names + 1] = n
        end
    end
    table.sort(names)
    return names
end

