local help = {
    'routes            list route files in data/routes',
    'load <name>       start a route      unload   stop it',
    'next / prev       step forward / back      goto <n>',
    'map               toggle small / large map (also ' .. (settings.map_key ~= '' and settings.map_key or 'no key') .. ')',
    'Alt + drag        move the map (small and large remember their own spot)',
    'hide / show       hide or show everything',
    'fix               save where you stand as the current waypoint\'s exact spot',
    'where             zone id, position, floor and grid square',
    'cal               put yourself on the map: Alt+click where you stand, twice',
    'cal reset|cancel  clear this floor\'s calibration / stop calibrating',
    'floor next|<id>|auto  flip to the zone\'s next map, force one, or back to automatic',
    'test              test route for any zone: walk a square, then NPC / item / kill steps',
}

windower.register_event('addon command', function(cmd, ...)
    local args = {...}
    cmd = cmd and cmd:lower() or 'help'

    if cmd == 'routes' then
        local names = list_routes()
        say(#names > 0 and ('routes: ' .. table.concat(names, ', ')) or 'no routes in data/routes')

    elseif cmd == 'load' and args[1] then
        local name = args[1]
        local r, err = load_lua('data/routes/' .. name .. '.lua')
        if r then
            set_route(name, r)
        else
            say('could not load route "' .. name .. '": ' .. tostring(err))
        end

    elseif cmd == 'unload' then
        route, route_name, step = nil, nil, nil
        say('route cleared')

    elseif cmd == 'next' then
        advance(1)
    elseif cmd == 'prev' then
        advance(-1)
    elseif cmd == 'goto' and tonumber(args[1]) and route then
        step = 1
        advance(tonumber(args[1]) - 1)

    elseif cmd == 'map' then
        settings.map_mode = settings.map_mode == 'large' and 'small' or 'large'
        config.save(settings)

    elseif cmd == 'hide' then
        settings.visible = false
        config.save(settings)
        hide_all()
    elseif cmd == 'show' then
        settings.visible = true
        config.save(settings)

    elseif cmd == 'fix' then
        local wp = route and route.waypoints[step]
        local me = windower.ffxi.get_mob_by_target('me')
        if not wp or not me then
            say('no current waypoint to fix')
            return
        end
        fixes[route_name] = fixes[route_name] or {}
        fixes[route_name][wp.id] = {x = me.x, y = me.y, z = me.z}
        save_fixes()
        say(('fixed "%s" at %.1f, %.1f, %.1f'):format(wp.name or wp.id, me.x, me.y, me.z))

    elseif cmd == 'where' then
        local me = windower.ffxi.get_mob_by_target('me')
        local zone_id = windower.ffxi.get_info().zone
        if not me then return end
        local floor = detect_floor(zone_id, me.x, me.y, me.z)
        local zn = res.zones[zone_id]
        say(('zone %d (%s)  x=%.1f y=%.1f z=%.1f  floor=%s  grid=%s'):format(zone_id,
            zn and zn.en or '?', me.x, me.y, me.z, floor and floor.id or 'none',
            game_to_grid(floor, me.x, me.y) or 'n/a'))

    elseif cmd == 'cal' then
        local me = windower.ffxi.get_mob_by_target('me')
        local zone_id = windower.ffxi.get_info().zone
        if not me then return end
        local floor = detect_floor(zone_id, me.x, me.y, me.z)
        local sub = args[1] and args[1]:lower()
        if sub == 'cancel' then
            calibrating = nil
            say('calibration cancelled')
        elseif not (floor and floor.map and floor.map.image) then
            say('no map image for this zone/floor - nothing to calibrate (see data/zones.lua)')
        elseif sub == 'reset' then
            calibration[floor.map.image] = nil
            save_calibration()
            say((floor.label or floor.id) .. ' calibration cleared')
        else
            calibrating = {floor = floor, image = floor.map.image, points = {}}
            settings.map_mode = 'large'
            say(('calibrating %s. Stand somewhere you can pin-point on the map (a room corner or doorway), '
                .. 'hold Alt and click that spot on the big map.'):format(floor.label or floor.id))
        end

    elseif cmd == 'floor' then
        local id = args[1] and args[1]:lower()
        local me = windower.ffxi.get_mob_by_target('me')
        local zone_id = windower.ffxi.get_info().zone
        local floors = zone_floors(zone_id)
        if id == 'next' and me and #floors > 0 then
            -- Flip to the zone's next map (dungeons often have several).
            local cur = detect_floor(zone_id, me.x, me.y, me.z)
            local i = 1
            for n, f in ipairs(floors) do
                if f == cur then i = n % #floors + 1 end
            end
            id = floors[i].id
        end
        floor_override = (id and id ~= 'auto') and id or nil
        if floor_override then
            local f = floor_by_id(zone_id, floor_override)
            say(('showing %s (//sn floor next to flip, //sn floor auto to undo)'):format(
                f and (f.label or f.id) or ('"' .. floor_override .. '" - no such map here')))
        else
            say('floor detection back to automatic')
        end

    elseif cmd == 'test' then
        test_route()
        -- The test square is exact positions, so on a real map it needs the
        -- map calibrated before the dots (and you) can be placed.
        local me = windower.ffxi.get_mob_by_target('me')
        local zone_id = windower.ffxi.get_info().zone
        local floor = me and detect_floor(zone_id, me.x, me.y, me.z)
        if floor and floor.map and floor.map.image and not transform(floor) then
            say('this zone has a real map, but it isn\'t calibrated yet: //sn cal and Alt+click where you '
                .. 'stand, twice, to see yourself and the test square on it.')
            if #zone_floors(zone_id) > 1 then
                say('this zone has several maps - //sn floor next until the one you\'re on shows, then //sn cal')
            end
        end

    else
        for _, line in ipairs(help) do
            say(line)
        end
    end
end)

windower.register_event('load', function()
    if settings.map_key ~= '' then
        windower.send_command('bind ' .. settings.map_key .. ' sn map')
    end
end)

windower.register_event('unload', function()
    if settings.map_key ~= '' then
        windower.send_command('unbind ' .. settings.map_key)
    end
end)
