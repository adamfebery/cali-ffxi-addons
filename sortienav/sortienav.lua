local dirs = {'E', 'NE', 'N', 'NW', 'W', 'SW', 'S', 'SE'}
local function compass(dx, dy)
    local i = math.floor(math.atan2(dy, dx) / (math.pi / 4) + 0.5) % 8
    return dirs[i + 1]
end

-- //sn cal state: {floor =, image =, points = {}} while calibrating.
local calibrating

local function render_readout(me, zone_id, floor)
    local lines = {}
    if not route then
        lines[1] = 'sortienav: no route  (//sn routes, //sn load <name>, //sn test)'
    else
        local wp = route.waypoints[step]
        lines[1] = ('%s  %s'):format(route.name or route_name,
            wp and ('step %d/%d'):format(step, #route.waypoints) or 'complete')
        if wp then
            local target = wp.name or ('#' .. step)
            local x, y, z, src = wp_pos(step)
            if wp_zone(wp) ~= zone_id then
                local zn = res.zones[wp_zone(wp)]
                lines[2] = ('Next: %s - in %s'):format(target, zn and zn.en or ('zone ' .. tostring(wp_zone(wp))))
            elseif wp.floor and (not floor or floor.id ~= wp.floor) then
                local f = floor_by_id(zone_id, wp.floor)
                lines[2] = ('Next: %s - go to %s'):format(target, f and f.label or wp.floor)
            elseif x then
                local dx, dy = x - me.x, y - me.y
                local h = ''
                if z and math.abs(z - me.z) > 4 then
                    h = ('  height %+d'):format(math.floor(z - me.z + 0.5))
                end
                lines[2] = ('Next: %s%s  %dy %s%s'):format(target, wp.grid and (' (' .. wp.grid .. ')') or '',
                    math.floor(math.sqrt(dx * dx + dy * dy) + 0.5), compass(dx, dy), h)
                if src == 'grid' then
                    lines[2] = lines[2] .. '  ~grid'
                end
            else
                -- Uncalibrated floor: the in-game map shows the same grid,
                -- so the square alone still gets you there.
                -- A step that is only an event (kill / item / NPC) and has no
                -- place at all just shows its name.
                lines[2] = wp.grid
                    and ('Next: %s  - map square %s'):format(target, wp.grid)
                    or (type(wp.advance) == 'table' and ('Next: ' .. target))
                    or ('Next: %s  (no position yet - //sn fix when there)'):format(target)
            end
            local kind = type(wp.advance) == 'table' and wp.advance.type or wp.advance
            if kind == 'defeat' or kind == 'item' or kind == 'device' then
                local verb = {defeat = 'defeat', item = 'obtain', device = 'use'}
                lines[#lines + 1] = ('Waiting: %s %s  (auto, or //sn next)'):format(verb[kind],
                    wp.advance.name or '')
            end
            if wp.note then
                lines[#lines + 1] = wp.note
            end
        end
    end
    if calibrating then
        lines[#lines + 1] = ('CALIBRATING %s: point %d/2 - Alt+click your exact spot on the big map'):format(
            calibrating.floor.label or calibrating.floor.id, #calibrating.points + 1)
        lines[#lines + 1] = 'Tip: open the in-game map to see where your arrow is. //sn cal cancel to stop.'
    elseif floor and floor.map and floor.map.image and not transform(floor) then
        lines[#lines + 1] = ('Map for %s not calibrated - //sn cal to put yourself on it'):format(floor.label or floor.id)
    end
    readout:text(table.concat(lines, '\n'))
    if not readout:visible() then
        readout:show()
    end
end

-- The view last drawn, for turning a click back into an image pixel:
-- {ox, oy, k, image = bool}.
local current_view

-- Sets up the background and returns the view:
--   game(x, y) -> screen x, y   (nil on an image that isn't calibrated yet)
--   px(u, v)   -> screen x, y   (image pixels; image mode only)
local function build_view(me, zone_id, floor, ox, oy, size)
    local T = transform(floor)
    local m = floor and floor.map
    if m and m.image then
        local w, h = m.width or 512, m.height or 512
        local k = size / math.max(w, h)
        local path = windower.addon_path .. 'maps/' .. m.image
        if bg_path ~= path then
            map_bg:path(path)
            map_bg:color(255, 255, 255)
            map_bg:alpha(235)
            bg_path = path
        end
        map_bg:pos(ox, oy)
        map_bg:size(math.floor(w * k), math.floor(h * k))
        current_view = {ox = ox, oy = oy, k = k, image = true}
        local view = {px = function(u, v) return ox + u * k, oy + v * k end}
        if T then
            view.game = function(x, y)
                return view.px(to_px(T, x, y))
            end
        end
        return view
    end

    -- No map image for this floor: plain dark box, auto-scaled to the
    -- waypoints on this floor plus you, north up.
    if bg_path ~= '' then
        map_bg:path('')
        map_bg:color(20, 20, 30)
        map_bg:alpha(190)
        bg_path = ''
    end
    map_bg:pos(ox, oy)
    map_bg:size(size, size)
    current_view = {ox = ox, oy = oy, image = false}

    local minx, maxx, miny, maxy = me.x, me.x, me.y, me.y
    if route then
        for i, wp in ipairs(route.waypoints) do
            if wp_zone(wp) == zone_id and (not wp.floor or (floor and floor.id == wp.floor)) then
                local x, y = wp_pos(i)
                if x then
                    minx, maxx = math.min(minx, x), math.max(maxx, x)
                    miny, maxy = math.min(miny, y), math.max(maxy, y)
                end
            end
        end
    end
    local span = math.max(maxx - minx, maxy - miny, 30) * 1.15
    local cx, cy = (minx + maxx) / 2, (miny + maxy) / 2
    local k = size / span
    return {game = function(x, y)
        return ox + size / 2 + (x - cx) * k, oy + size / 2 - (y - cy) * k
    end}
end

-- Screen position of waypoint i. Exact positions (fix / pos) go through the
-- calibration; a guide square can go straight onto the image by its grid
-- pixel, even before calibration.
local function wp_screen(i, wp, view, floor)
    local x, y, _, src = wp_pos(i)
    if x and src ~= 'grid' and view.game then
        return view.game(x, y)
    end
    if view.px and wp.grid then
        local u, v = grid_to_px(floor, wp.grid)
        if u then
            return view.px(u, v)
        end
    end
    if x and view.game then
        return view.game(x, y)
    end
end

local function render_map(me, zone_id, floor)
    local big = settings.map_mode == 'large'
    local cfg = big and settings.large or settings.small
    local view = build_view(me, zone_id, floor, cfg.x, cfg.y, cfg.size)
    if not map_bg:visible() then
        map_bg:show()
    end

    local dot, pdot = big and 8 or 5, big and 11 or 7
    local used_dots, used_trail = 0, 0
    local next_placed = false
    if route then
        local prev_sx, prev_sy
        for i, wp in ipairs(route.waypoints) do
            local sx, sy
            if wp_zone(wp) == zone_id and (not wp.floor or (floor and floor.id == wp.floor)) then
                sx, sy = wp_screen(i, wp, view, floor)
            end
            if sx then
                if i == step then
                    place(next_dot, sx, sy, dot + 4)
                    next_placed = true
                elseif used_dots < #dots then
                    used_dots = used_dots + 1
                    local d = dots[used_dots]
                    if i < step then
                        d:color(120, 120, 120)
                    else
                        d:color(0, 200, 255)
                    end
                    place(d, sx, sy, dot)
                end
                -- Dotted trail along the rest of the route (from the current step on).
                if prev_sx and i > step then
                    local len = math.sqrt((sx - prev_sx) ^ 2 + (sy - prev_sy) ^ 2)
                    local n = math.floor(len / 6)
                    for j = 1, n - 1 do
                        if used_trail >= #trail then break end
                        used_trail = used_trail + 1
                        place(trail[used_trail], prev_sx + (sx - prev_sx) * j / n, prev_sy + (sy - prev_sy) * j / n, 2)
                    end
                end
                if i >= step then
                    prev_sx, prev_sy = sx, sy
                end
            end
        end
    end
    if not next_placed and next_dot:visible() then
        next_dot:hide()
    end
    hide_from(dots, used_dots + 1)
    hide_from(trail, used_trail + 1)

    -- You: only where the map knows where you are (calibrated, or dot mode).
    if view.game then
        local sx, sy = view.game(me.x, me.y)
        place(player_dot, sx, sy, pdot)
    elseif player_dot:visible() then
        player_dot:hide()
    end
end

local function try_advance(me, zone_id, floor)
    local wp = route and route.waypoints[step]
    if not wp then
        return
    end
    local rule = wp.advance or 'arrive'
    local kind = type(rule) == 'table' and rule.type or rule
    if kind == 'arrive' then
        if wp_zone(wp) ~= zone_id or (wp.floor and (not floor or floor.id ~= wp.floor)) then
            return
        end
        local x, y = wp_pos(step)
        if x then
            local dx, dy = x - me.x, y - me.y
            local r = wp.radius or settings.arrive_radius
            if dx * dx + dy * dy <= r * r then
                advance(1, 'arrived')
            end
        end
    elseif kind == 'floor' then
        if zone_id == wp_zone(wp) and floor and floor.id == rule.floor then
            advance(1, 'floor')
        end
    elseif kind == 'zone' then
        if zone_id == rule.zone then
            advance(1, 'zone')
        end
    end
    -- defeat / item / device are driven by the event handlers below.
end

