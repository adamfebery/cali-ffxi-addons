-- Advances if the current waypoint waits on `kind` and `name` contains its
-- advance.name (case-insensitive, so "Gadget #A" matches the NPC
-- "Diaphanous Gadget #A"). One direction only: a stray short chat fragment
-- like "a" must not match "Ra'Kaznar Shard A".
local function event_fired(kind, name, why)
    local wp = route and route.waypoints[step]
    local rule = wp and wp.advance
    if type(rule) ~= 'table' or rule.type ~= kind or not name then
        return
    end
    local want, got = (rule.name or ''):lower(), name:lower()
    if want == '' or got:find(want, 1, true) then
        advance(1, why)
    end
end

local DEFEAT_MESSAGES = S{6, 20, 113, 406, 605, 646}

local function defeated(target_id)
    local mob = windower.ffxi.get_mob_by_id(target_id)
    if mob then
        event_fired('defeat', mob.name, mob.name .. ' defeated')
    end
end

-- "X defeats Y" / "Y falls to the ground" arrive either as a bare message...
windower.register_event('action message', function(actor_id, target_id, actor_index, target_index, message_id)
    if DEFEAT_MESSAGES:contains(message_id) then
        defeated(target_id)
    end
end)

-- ...or folded into the action that landed the killing blow.
windower.register_event('action', function(act)
    for _, target in ipairs(act.targets or {}) do
        for _, a in ipairs(target.actions or {}) do
            if DEFEAT_MESSAGES:contains(a.message) or DEFEAT_MESSAGES:contains(a.add_effect_message) then
                defeated(target.id)
            end
        end
    end
end)

-- Items, including Sortie's temporary items (Shard / Key / Plate ...).
windower.register_event('add item', function(bag, index, id)
    local item = res.items[id]
    if item then
        event_fired('item', item.en, item.en .. ' obtained')
        event_fired('item', item.enl, item.en .. ' obtained')
    end
end)

-- Key items and anything the add item event misses: the chat line.
windower.register_event('incoming text', function(original)
    if not route then
        return
    end
    local text = windower.convert_auto_trans(original):strip_format()
    local what = text:match('[Oo]btained key item: (.-)%.?$')
        or text:match('[Oo]btained temporary item: (.-)%.?$')
        or text:match('obtains? an? (.-)%.?$')
        or text:match('obtains? (.-)%.?$')
    if what then
        event_fired('item', what, what .. ' obtained')
    end
end)

-- Talking to / touching an NPC (gates, gadgets, devices, Bitzer) is an
-- outgoing action packet with category 0.
windower.register_event('outgoing chunk', function(id, data)
    if id ~= 0x01A or not route then
        return
    end
    local p = packets.parse('outgoing', data)
    if p and p.Category == 0 then
        local mob = windower.ffxi.get_mob_by_id(p.Target)
        if mob then
            event_fired('device', mob.name, mob.name .. ' used')
        end
    end
end)

local last_update = 0

